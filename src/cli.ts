#!/usr/bin/env node
/**
 * Universal Workspace MCP — management CLI.
 *
 *   npm run setup           # first-run: create .env (if missing), seed owner user + admin token
 *   npm run mint-token      # mint a new token for a user/agent
 *   npm run list-tokens
 *   npm run revoke-token <token-id>
 *   npm run list-workspaces
 *   npx tsx src/cli.ts status
 */
import { parseArgs } from "node:util";
import { randomBytes, randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { openDatabase, reapStaleState } from "./database/db.js";
import { loadConfig } from "./config/env.js";
import { mintToken, revokeToken } from "./security/authenticate.js";

const PROJECT_ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const ENV_PATH = path.join(PROJECT_ROOT, ".env");

function ensureEnvFile(): boolean {
  if (fs.existsSync(ENV_PATH)) return false;
  const pepper = randomBytes(48).toString("base64");
  const template = `# Generated by \`npm run setup\` on ${new Date().toISOString()}
HOST=127.0.0.1
PORT=3333
DATA_DIR=./data
TOKEN_PEPPER=${pepper}
LOG_LEVEL=info
EXEC_MODE=restricted
EXEC_DEFAULT_TIMEOUT_MS=120000
EXEC_MAX_TIMEOUT_MS=600000
EXEC_MAX_OUTPUT_BYTES=1048576
EXEC_MAX_CONCURRENT_PER_WORKSPACE=5
MAX_FILE_BYTES=5242880
RATE_LIMIT_PER_MIN=120
EVENT_RETENTION_DAYS=90
GIT_ENABLED_DEFAULT=true
`;
  fs.writeFileSync(ENV_PATH, template, { mode: 0o600 });
  return true;
}

function loadEnv(): void {
  try {
    process.loadEnvFile(ENV_PATH);
  } catch (error) {
    // --env-file not required when .env was just created (setup handles it), or when missing for real
    if (fs.existsSync(ENV_PATH)) throw error;
  }
}

function freshDb() {
  loadEnv();
  const config = loadConfig();
  fs.mkdirSync(config.workspacesDir, { recursive: true });
  fs.mkdirSync(config.backupsDir, { recursive: true });
  fs.mkdirSync(config.tmpDir, { recursive: true });
  const db = openDatabase(config.databasePath);
  reapStaleState(db);
  return { config, db };
}

function printTokenOnce(prefix: string, token: string): void {
  const line = "─".repeat(72);
  // eslint-disable-next-line no-console
  console.log(`\n${line}\n  ${prefix} (shown ONCE — store it now)\n\n  ${token}\n${line}\n`);
}

const cmd = process.argv[2];

try {
  switch (cmd) {
    case "setup": {
      const created = ensureEnvFile();
      if (created) {
        // eslint-disable-next-line no-console
        console.log(`✔ created .env (mode 600) with a fresh TOKEN_PEPPER`);
      }
      const { config, db } = freshDb();

      const userCount = (db.prepare(`SELECT COUNT(*) AS c FROM users`).get() as { c: number }).c;
      if (userCount > 0) {
        // eslint-disable-next-line no-console
        console.log(`✔ database ready at ${config.databasePath} (${userCount} user(s) exist — not minting a new token)`);
        console.log(`  mint a token with:  npm run mint-token -- --name my-agent`);
        db.close();
        break;
      }

      // First run: create owner + agent + admin token
      const userId = randomUUID();
      db.prepare(`INSERT INTO users (id, display_name, role) VALUES (?, 'owner', 'owner')`).run(userId);
      const agentId = randomUUID();
      db.prepare(`INSERT INTO agents (id, user_id, name, kind) VALUES (?, ?, 'setup-cli', 'cli')`).run(agentId, userId);
      const { token } = mintToken(db, config.tokenPepper, { userId, agentId, name: "initial-admin", scopes: [] });

      // eslint-disable-next-line no-console
      console.log(`✔ database ready at ${config.databasePath}`);
      console.log(`✔ created owner user (display_name: owner)`);
      console.log(`✔ minted admin token for agent 'setup-cli'`);
      printTokenOnce("ADMIN TOKEN", token);
      console.log(`Set it in your agent's MCP config, e.g.:`);
      console.log(`  Authorization: Bearer ${token}\n`);
      db.close();
      break;
    }

    case "mint-token": {
      const { values } = parseArgs({
        args: process.argv.slice(3),
        options: {
          name: { type: "string", default: "agent" },
          agent: { type: "string" },
          user: { type: "string" },
          scopes: { type: "string", default: "" },
          expires_days: { type: "string" },
        },
      });
      const { config, db } = freshDb();
      const users = values.user
        ? [db.prepare(`SELECT * FROM users WHERE id = ? OR display_name = ?`).get(values.user, values.user) as { id: string; display_name: string; role: string } | undefined]
        : (db.prepare(`SELECT * FROM users ORDER BY created_at ASC`).all() as unknown as { id: string; display_name: string; role: string }[]);
      const user = users?.[0];
      if (!user) throw new Error("no user found — run `npm run setup` first");

      let agentId: string | null = null;
      if (values.agent) {
        const existing = db.prepare(`SELECT id FROM agents WHERE user_id = ? AND name = ?`).get(user.id, values.agent) as { id: string } | undefined;
        if (existing) {
          agentId = existing.id;
        } else {
          agentId = randomUUID();
          db.prepare(`INSERT INTO agents (id, user_id, name, kind) VALUES (?, ?, ?, 'agent')`).run(agentId, user.id, values.agent);
        }
      }

      const scopes = values.scopes ? values.scopes.split(",").map((s) => s.trim()).filter(Boolean) : [];
      const expiresAt = values.expires_days ? new Date(Date.now() + Number(values.expires_days) * 86_400_000).toISOString() : null;
      const { id, token } = mintToken(db, config.tokenPepper, { userId: user.id, agentId, name: values.name ?? "agent", scopes, expiresAt });

      // eslint-disable-next-line no-console
      console.log(`✔ token id: ${id}  (user: ${user.display_name}, scopes: ${scopes.length ? scopes.join(",") : "inherit role"})`);
      printTokenOnce(`TOKEN '${values.name}'`, token);
      db.close();
      break;
    }

    case "list-tokens": {
      const { db } = freshDb();
      const rows = db.prepare(
        `SELECT t.id, t.name, t.scopes, t.expires_at, t.last_used_at, t.created_at, t.revoked_at,
                a.name AS agent_name, u.display_name AS user_name
         FROM access_tokens t
         JOIN users u ON u.id = t.user_id
         LEFT JOIN agents a ON a.id = t.agent_id
         ORDER BY t.created_at DESC`
      ).all() as unknown as Array<Record<string, unknown>>;
      for (const row of rows) {
        // eslint-disable-next-line no-console
        console.log(JSON.stringify(row, null, 2));
      }
      console.log(`\n${rows.length} token(s)`);
      db.close();
      break;
    }

    case "revoke-token": {
      const tokenId = process.argv[3];
      if (!tokenId) throw new Error("usage: revoke-token <token-id>");
      const { db } = freshDb();
      const ok = revokeToken(db, tokenId);
      // eslint-disable-next-line no-console
      console.log(ok ? `✔ token ${tokenId} revoked` : `token ${tokenId} not found or already revoked`);
      db.close();
      break;
    }

    case "list-workspaces": {
      const { db } = freshDb();
      const rows = db.prepare(`SELECT slug, name, type, git_enabled, archived_at, created_at, root_path FROM workspaces ORDER BY created_at`).all() as unknown as Array<Record<string, unknown>>;
      for (const row of rows) {
        // eslint-disable-next-line no-console
        console.log(`${row.archived_at ? "[archived] " : ""}${row.slug} — ${row.name} (${row.type}, git: ${row.git_enabled ? "on" : "off"})\n    ${row.root_path}`);
      }
      if (rows.length === 0) console.log("no workspaces yet — create one with the workspace_create MCP tool");
      db.close();
      break;
    }

    case "status": {
      const { config, db } = freshDb();
      const counts = (table: string) => (db.prepare(`SELECT COUNT(*) AS c FROM ${table}`).get() as { c: number }).c;
      // eslint-disable-next-line no-console
      console.log(`config:       ${config.dataDir}`);
      console.log(`users:        ${counts("users")}`);
      console.log(`agents:       ${counts("agents")}`);
      console.log(`tokens:       ${counts("access_tokens")} (active: ${(db.prepare(`SELECT COUNT(*) AS c FROM access_tokens WHERE revoked_at IS NULL`).get() as { c: number }).c})`);
      console.log(`workspaces:   ${counts("workspaces")}`);
      console.log(`sessions:     ${counts("sessions")} (active: ${(db.prepare(`SELECT COUNT(*) AS c FROM sessions WHERE status = 'active'`).get() as { c: number }).c})`);
      console.log(`events:       ${counts("events")}`);
      db.close();
      break;
    }

    default: {
      // eslint-disable-next-line no-console
      console.log(`usage:
  npm run setup                 first-run: .env + owner user + admin token
  npm run mint-token            [-- --name opencode-phone --agent opencode-phone --scopes a,b]
  npm run list-tokens
  npm run revoke-token <id>
  npm run list-workspaces
  npx tsx src/cli.ts status`);
      process.exit(cmd ? 1 : 0);
    }
  }
} catch (error) {
  // eslint-disable-next-line no-console
  console.error("error:", error instanceof Error ? error.message : error);
  process.exit(1);
}
